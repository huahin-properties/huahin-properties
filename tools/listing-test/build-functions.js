#!/usr/bin/env node
// LISTING-E2E-01 — builds a SEPARATE, listing-only Cloud Functions source folder (build/listing-functions) from the production sources, editing nothing.
// WHY: `firebase deploy --only functions:<names>` still loads the WHOLE functions/index.js, and the Firebase CLI resolves EVERY defineSecret() declared
// there (ANTHROPIC / STRIPE / RESEND / LINE …) against Secret Manager BEFORE it applies --only. On a project without those secrets (or without the Secret
// Manager API) the deploy stops with HTTP 403 even though none of the 9 listing functions uses a secret. The listing functions live in listing-case.js,
// which needs no secret, so they are deployed from a folder that contains only them.
//   node tools/listing-test/build-functions.js [--out build/listing-functions]
// Fails closed if the source changed shape. Copies files byte-for-byte; the 9 export definitions are taken verbatim from functions/index.js.
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.resolve(__dirname, "..", "..");
const NAMES = ["submitListingCase", "previewListingCase", "publishListingCase", "unpublishListingCase", "syncListingCase", "addCasePhotos", "reconcileListingFiles", "listMyCases", "trackListingCase"];
const FILES = ["listing-case.js", "photo-standard.js", "case-fields.js", "submission-checklist.js"];
function fail(m) { const e = new Error(m); e.listingFunctions = true; throw e; }

function build(root, outDir) {
  root = root || ROOT;
  const fdir = path.join(root, "functions");
  const idx = fs.readFileSync(path.join(fdir, "index.js"), "utf8");
  const a = idx.indexOf('const listingCase = require("./listing-case");');
  const b = idx.indexOf("// startConversation (Callable)");
  if (a < 0 || b < a) fail("listing block not found in functions/index.js — source changed, refusing");
  const block = idx.slice(a, b);
  const exported = Array.from(block.matchAll(/^exports\.([A-Za-z]+) = /gm)).map((m) => m[1]);
  if (JSON.stringify(exported.slice().sort()) !== JSON.stringify(NAMES.slice().sort())) fail("the listing block exports " + exported.join(",") + " — expected exactly " + NAMES.join(","));
  if (/secrets\s*:|defineSecret|ANTHROPIC|STRIPE|chatGate/.test(block)) fail("the listing block references a secret or the chat gate — refusing");
  const pkg = JSON.parse(fs.readFileSync(path.join(fdir, "package.json"), "utf8"));
  const out = path.resolve(outDir || path.join(root, "build", "listing-functions"));
  if (!out.startsWith(path.join(root, "build") + path.sep)) fail("output must be inside ./build");
  fs.rmSync(out, { recursive: true, force: true }); fs.mkdirSync(out, { recursive: true });
  for (const f of FILES) {
    const src = fs.readFileSync(path.join(fdir, f), "utf8");
    for (const m of src.matchAll(/require\("(\.\/[^"]+)"\)/g)) if (!FILES.includes(m[1].slice(2) + ".js")) fail(f + " requires " + m[1] + " which is not in the listing-only set");
    fs.copyFileSync(path.join(fdir, f), path.join(out, f));
  }
  fs.writeFileSync(path.join(out, "index.js"),
    "// GENERATED by tools/listing-test/build-functions.js — listing-only functions (no secrets). Do not edit.\n" +
    'const { onCall, HttpsError } = require("firebase-functions/v2/https");\nconst admin = require("firebase-admin");\nif (!admin.apps.length) admin.initializeApp();\n' + block);
  fs.writeFileSync(path.join(out, "package.json"), JSON.stringify({ name: "listing-functions", private: true, engines: pkg.engines, main: "index.js",
    dependencies: { "firebase-functions": pkg.dependencies["firebase-functions"], "firebase-admin": pkg.dependencies["firebase-admin"] } }, null, 2) + "\n");
  fs.writeFileSync(path.join(out, "firebase.json"), JSON.stringify({ functions: [{ source: ".", codebase: "listing", ignore: ["node_modules", ".git", "firebase-debug.log"] }] }, null, 2) + "\n");
  return { out, files: fs.readdirSync(out).sort(), names: NAMES };
}
module.exports = { build, NAMES, FILES };
if (require.main === module) {
  try { const i = process.argv.indexOf("--out"); const r = build(ROOT, i > 0 ? process.argv[i + 1] : null); console.log("listing-only functions folder written: " + path.relative(ROOT, r.out) + " (" + r.files.join(", ") + ")"); }
  catch (e) { console.error("LISTING FUNCTIONS BUILD REFUSED: " + e.message); process.exit(1); }
}
